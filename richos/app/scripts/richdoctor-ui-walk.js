async function contrast(page, name, theme) {
  await page.addScriptTag({ content: pageScript() });
  const r = await page.evaluate(({ surface, theme }) => window.__contrastProbe({ surface, theme }), { surface: name, theme });
  const keys = (o) => Object.keys(o || {});
  const fails = keys(r.failures).length + keys(r.indicators && r.indicators.failures).length;
  if (fails) bad(`contrast ${name} ${theme}`, JSON.stringify(Object.assign({}, r.failures, r.indicators && r.indicators.failures)).slice(0, 1500));
  else ok(`contrast ${name} ${theme}: ${r.nodesPassed}/${r.nodesChecked} text, ${r.indicators.passed}/${r.indicators.checked} indicators`);
}

