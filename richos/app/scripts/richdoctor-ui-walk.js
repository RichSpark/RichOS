let failures = 0;
function ok(name) { console.log("ok   " + name); }
function bad(name, why) { failures++; console.log("FAIL " + name + ": " + why); }
function check(name, cond, why) { if (cond) ok(name); else bad(name, why || "not as expected"); }

// ---- a scratch copy of the window, with the generated files build.rs writes ------------------
function stage() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "rd-ui-"));
  for (const f of fs.readdirSync(UI)) {
    const src = path.join(UI, f);
    if (fs.statSync(src).isFile()) fs.copyFileSync(src, path.join(dir, f));
  }
  fs.mkdirSync(path.join(dir, "fonts"));
  for (const f of fs.readdirSync(path.join(APP, "ui", "fonts"))) fs.copyFileSync(path.join(APP, "ui", "fonts", f), path.join(dir, "fonts", f));
  const css = fs.readFileSync(path.join(APP, "ui", "style.css"), "utf8").split("\n");
  const block = (head) => { const s = css.findIndex((l) => l.trimEnd() === head); const e = css.slice(s).indexOf("}"); return css.slice(s, s + e + 1).join("\n"); };
  fs.writeFileSync(path.join(dir, "tokens.css"), block(":root {") + "\n\n" + block(':root[data-theme="light"] {') + "\n");
  return dir;
}

